const fs=require('node:fs');
const ts=require('typescript');
const assert=require('node:assert/strict');
(async()=>{
 const source=fs.readFileSync(new URL('../src/timeSeries.ts',require('node:url').pathToFileURL(__filename)),'utf8');
 const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022}}).outputText;
 const {appendHours,inspectTimeSeries}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
 const annual=appendHours('','2025-01-01T00:00',8760);
 assert.deepEqual(inspectTimeSeries(annual),{count:8760,issues:[],totalIssues:0});
 assert.match(annual,/2025-12-31 23:00:00/);
 const made=appendHours('','2026-12-31T23:00',2);
 assert.equal(inspectTimeSeries(made).totalIssues,0);
 assert.match(appendHours(made,'2026-01-01T00:00',1),/2027-01-01 01:00:00/);
 assert.throws(()=>appendHours('','2026-02-30T00:00',2));
 assert.throws(()=>appendHours(made,'2026-01-01T00:00',8760));
 const bad=inspectTimeSeries(made.replace('2027-01-01 00:00:00,0,0,0','2027-01-01 02:00:00,-1,,Infinity'));
 assert.equal(bad.totalIssues,4);assert.ok(bad.issues.every(x=>x.row===3));
 assert.equal(inspectTimeSeries(made.replaceAll(':00:00',':30:00')).totalIssues,0);
 assert.equal(inspectTimeSeries(made.replaceAll(':00:00',':00:00.000')).totalIssues,0);
 assert.equal(inspectTimeSeries(made.replaceAll(':00:00',':00:00.123')).totalIssues,0);
 assert.ok(inspectTimeSeries('').totalIssues>0);
 assert.ok(inspectTimeSeries(made.replace('2026-12-31','2026-02-30')).issues.some(x=>x.row===2));
 assert.ok(inspectTimeSeries(made.replace('timestamp,','time,')).issues.some(x=>x.row===1));
 const many=inspectTimeSeries(appendHours('','2026-01-01T00:00',30).replaceAll(',0,0,0',',-1,-1,-1'));
 assert.equal(many.totalIssues,90);assert.equal(many.issues.length,20);
 console.log('PASS: 时序建立、跨年追加、无效日期、上限、错误行号、非整点连续时序、空值/负值/无穷、表头和问题数量限制');
})();
